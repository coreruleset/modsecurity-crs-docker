#!/bin/sh
# vim:sw=2:ts=2:sts=2:et

set -eu

LC_ALL=C
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

# Configure the CA certificates used to verify TLS client certificates
# (mutual TLS) for incoming connections. ssl_verify_client and
# ssl_verify_depth are set from SSL_VERIFY and SSL_VERIFY_DEPTH in
# conf.d/default.conf. The ssl_client_certificate and ssl_crl directives and
# the identity forwarding headers live in the generated includes
# includes/client_ca.conf and includes/client_identity.conf, which start out
# empty, so the default configuration runs without client certificate
# verification. nginx refuses to start when ssl_verify_client is enabled
# without CA certificates, so a missing file is a hard error unless
# SSL_VERIFY=optional_no_ca.
# SSL_CLIENT_CA_REVOCATION_FILE adds an ssl_crl directive to the generated
# include to reject revoked client certificates; a configured revocation file
# always enables checking (ssl_crl has no off mode short of not using it).
#
# When SSL_VERIFY is off the script is a no-op: it does not write to the
# configuration directory, so it also works when that directory is read-only.

VERIFY="${SSL_VERIFY:-off}"

case "${VERIFY}" in
    off)
        echo "${0}: client certificate verification disabled"
        exit 0
        ;;
    on|optional|optional_no_ca)
        ;;
    *)
        echo "${0}: invalid SSL_VERIFY value, expected one of: off, on, optional, optional_no_ca" >&2
        exit 1
        ;;
esac

# The values shared with the Apache startup script are validated in one place.
check-ssl-client-verify-env

REVOCATION_FILE="${SSL_CLIENT_CA_REVOCATION_FILE:-}"
REVOCATION_CHECK="${SSL_CLIENT_CA_REVOCATION_CHECK:-none}"
HEADER_PREFIX="${SSL_CLIENT_HEADER_PREFIX:-X-SSL-}"

if [ -n "${REVOCATION_FILE}" ] && [ ! -r "${REVOCATION_FILE}" ]; then
    echo "${0}: SSL_CLIENT_CA_REVOCATION_FILE does not name a readable file, refusing to start" >&2
    exit 1
fi

case "${REVOCATION_CHECK}" in
    none|chain)
        ;;
    leaf)
        echo "${0}: SSL_CLIENT_CA_REVOCATION_CHECK=leaf is not supported on nginx, ssl_crl always checks the whole certificate chain, refusing to start" >&2
        exit 1
        ;;
    *)
        echo "${0}: invalid SSL_CLIENT_CA_REVOCATION_CHECK value, expected one of: none, chain" >&2
        exit 1
        ;;
esac

# A configured revocation file must not end up unused: without ssl_crl nginx
# does not look at the CRLs at all and accepts revoked certificates, so the
# check defaults to chain (the whole certificate chain, the only mode ssl_crl
# has) in that case.
if [ -n "${REVOCATION_FILE}" ] && [ "${REVOCATION_CHECK}" = "none" ]; then
    REVOCATION_CHECK="chain"
    echo "${0}: SSL_CLIENT_CA_REVOCATION_FILE is set, defaulting SSL_CLIENT_CA_REVOCATION_CHECK to chain"
fi

if [ "${REVOCATION_CHECK}" != "none" ] && [ -z "${REVOCATION_FILE}" ]; then
    echo "${0}: SSL_CLIENT_CA_REVOCATION_CHECK=${REVOCATION_CHECK} requires SSL_CLIENT_CA_REVOCATION_FILE, refusing to start" >&2
    exit 1
fi

mkdir -p /etc/nginx/includes || {
    echo "${0}: cannot create /etc/nginx/includes, refusing to start" >&2
    exit 1
}

if [ -n "${SSL_CLIENT_CA_CERT_FILE:-}" ] && [ -r "${SSL_CLIENT_CA_CERT_FILE}" ]; then
    {
        echo "# Generated by update-ssl-client-verify-config at start."
        echo "ssl_client_certificate \"${SSL_CLIENT_CA_CERT_FILE}\";"
        if [ -n "${REVOCATION_FILE}" ]; then
            echo "ssl_crl \"${REVOCATION_FILE}\";"
        fi
    } > /etc/nginx/includes/client_ca.conf || {
        echo "${0}: cannot write /etc/nginx/includes/client_ca.conf, refusing to start" >&2
        exit 1
    }
    echo "${0}: verifying client certificates against ${SSL_CLIENT_CA_CERT_FILE}"
elif [ "${VERIFY}" = "optional_no_ca" ]; then
    echo "${0}: accepting client certificates without verifying them (SSL_VERIFY=${VERIFY})"
else
    echo "${0}: SSL_VERIFY=${VERIFY} requires SSL_CLIENT_CA_CERT_FILE to name a readable file, refusing to start" >&2
    exit 1
fi

{
    echo "# Generated by update-ssl-client-verify-config at start. The client"
    echo "# certificate identity is only forwarded when the client presented a"
    echo "# certificate that verified successfully (${HEADER_PREFIX}Client-Verify:"
    echo "# SUCCESS): the claimed subject of a certificate accepted without"
    echo "# verification (optional_no_ca) is not an identity. The verification"
    echo "# result itself is forwarded whenever a certificate was presented."
    echo "# proxy_set_header replaces client-supplied headers, and headers with an"
    echo "# empty value are dropped, which keeps both headers out of requests"
    echo "# without a client certificate."
    echo "proxy_set_header ${HEADER_PREFIX}Client-DN \$ssl_client_dn_header;"
    echo "proxy_set_header ${HEADER_PREFIX}Client-Verify \$ssl_client_verify_header;"
} > /etc/nginx/includes/client_identity.conf || {
    echo "${0}: cannot write /etc/nginx/includes/client_identity.conf, refusing to start" >&2
    exit 1
}
