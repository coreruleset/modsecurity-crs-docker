#!/bin/sh
# vim:sw=2:ts=2:sts=2:et

set -eu

LC_ALL=C
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

# Configure the CA certificates used to verify TLS client certificates
# (mutual TLS) for incoming connections. ssl_verify_client and
# ssl_verify_depth are set from SSL_VERIFY and SSL_VERIFY_DEPTH in
# conf.d/default.conf; the ssl_client_certificate directive references a file
# and is only generated when that file is present, so the default
# configuration starts without client certificate verification. nginx refuses
# to start when ssl_verify_client is enabled without CA certificates, so a
# missing file is a hard error unless SSL_VERIFY=optional_no_ca.

CLIENT_VERIFY_CONFIG=""
VERIFY="${SSL_VERIFY:-off}"

# These values end up in webserver configuration files; reject the characters
# that could break out of the directive they are written to.
check_config_value() {
    if printf '%s' "${2}" | LC_ALL=C grep -q -e '[";{}\\`$]' -e '[^ -~]'; then
        echo "${0}: ${1} contains unsupported characters, refusing to start" >&2
        exit 1
    fi
}

case "${SSL_VERIFY_DEPTH-1}" in
    '' | *[!0-9]*)
        echo "${0}: invalid SSL_VERIFY_DEPTH value, expected a number" >&2
        exit 1
        ;;
esac

check_config_value SSL_CLIENT_CA_CERT_FILE "${SSL_CLIENT_CA_CERT_FILE:-}"

case "${VERIFY}" in
    off)
        echo "${0}: client certificate verification disabled"
        ;;
    on|optional|optional_no_ca)
        if [ -n "${SSL_CLIENT_CA_CERT_FILE:-}" ] && [ -r "${SSL_CLIENT_CA_CERT_FILE}" ]; then
            mkdir -p /etc/nginx/includes
            {
                echo "# Generated by update-ssl-client-verify-config at start."
                echo "ssl_client_certificate \"${SSL_CLIENT_CA_CERT_FILE}\";"
            } > /etc/nginx/includes/client_ca.conf || {
                echo "${0}: cannot write /etc/nginx/includes/client_ca.conf, refusing to start" >&2
                exit 1
            }
            CLIENT_VERIFY_CONFIG="include includes/client_ca.conf;"
            echo "${0}: verifying client certificates against ${SSL_CLIENT_CA_CERT_FILE}"
        elif [ "${VERIFY}" = "optional_no_ca" ]; then
            echo "${0}: accepting client certificates without verifying them (SSL_VERIFY=${VERIFY})"
        else
            echo "${0}: SSL_VERIFY=${VERIFY} requires SSL_CLIENT_CA_CERT_FILE to name a readable file, refusing to start" >&2
            exit 1
        fi
        ;;
    *)
        echo "${0}: invalid SSL_VERIFY value, expected one of: off, on, optional, optional_no_ca" >&2
        exit 1
        ;;
esac

if [ -z "${CLIENT_VERIFY_CONFIG}" ]; then
    rm -f /etc/nginx/includes/client_ca.conf
fi

sed -i.bak -r 's#CLIENT_VERIFY_CONFIG#'"${CLIENT_VERIFY_CONFIG}"'#' /etc/nginx/conf.d/default.conf
